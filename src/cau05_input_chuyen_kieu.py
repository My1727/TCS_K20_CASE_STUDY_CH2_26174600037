ma_may = input("Nhap ma may: ")
cong_suat_w = input("Nhap cong suat W: ")
so_phut = input("Nhap so phut su dung: ")
don_gia_kwh = input("Nhap đon gia dien/kWh: ")
print("Ma may: ", ma_may, ",Kieu: ", type(ma_may))
print("Cong suat ban đau:", cong_suat_w, "| Kieu:", type(cong_suat_w))
print("So phut ban đau:", so_phut, "| Kieu:", type(so_phut))
print("Đon gia ban đau:", don_gia_kwh, "| Kieu:", type(don_gia_kwh))
cong_suat_w = float(cong_suat_w)
so_phut = int(so_phut)
don_gia_kwh = float(don_gia_kwh)
print("Kieu cua cong_suat_w sau khi ep kieu:", type(cong_suat_w))
print("Kieu cua so_phut sau khi ep kieu:", type(so_phut))
print("Kieu cua don_gia_kwh sau khi ep kieu:", type(don_gia_kwh))
dien_nang_kwh = cong_suat_w * so_phut / 60 / 1000
chi_phi = dien_nang_kwh * don_gia_kwh
print("Đien nang tieu thu (kWh):", dien_nang_kwh)
print("Chi phi đien (VND):", chi_phi)